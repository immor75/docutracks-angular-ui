// Production build at /apps-next/: editor + Formio load with no failed requests; bytes per step.
import { chromium } from 'playwright';
const BASE = 'http://localhost:4400/apps-next/';
const browser = await chromium.launch({ executablePath: '/opt/pw-browsers/chromium' });
const page = await (await browser.newContext({ viewport: { width: 1440, height: 900 } })).newPage();
page.setDefaultTimeout(15000);
const bad = [], bytes = { js: 0, css: 0, other: 0 };
let phase = 'list';
const per = {};
page.on('requestfailed', (r) => bad.push(r.url()));
page.on('console', (m) => m.type() === 'error' && bad.push('console ' + m.text().slice(0, 300)));
page.on('pageerror', (e) => bad.push('pageerror ' + String(e).slice(0, 300)));
page.on('response', async (r) => {
  if (r.status() >= 400) bad.push(r.status() + ' ' + r.url());
  const len = Number((await r.allHeaders())['content-length'] ?? 0) || (await r.body().catch(() => Buffer.alloc(0))).length;
  per[phase] = (per[phase] ?? 0) + len;
});
await fetch('http://localhost:3001/__mock/reset/?data=1');
await page.goto(BASE + 'login');
await page.fill('input[name=username]', 'admin'); await page.fill('input[name=password]', 'admin');
await page.click('button[type=submit]'); await page.waitForSelector('app-type-nav a');
await page.getByRole('link', { name: 'Ανάθεση Εργασίας', exact: true }).click();
await page.waitForFunction(() => document.querySelector('app-pager')?.textContent?.includes('1240'));
phase = 'editor';
let t = Date.now();
await page.getByRole('button', { name: /Νέα υπόθεση/ }).click();
await page.waitForSelector('app-editor-page #f-FolderName');
console.log('editor ready ms', Date.now() - t);
phase = 'formio';
t = Date.now();
await page.locator('app-editor-page [role=tab]', { hasText: 'Ειδικά' }).click();
await page.locator('app-formio-form .fx[data-ready] .formio-component-metadataTitle input').waitFor().catch(async () => console.log('fx state', await page.locator('app-formio-form').innerText()));
console.log('formio ready ms', Date.now() - t);
await page.locator('.formio-component-datetime .input-group').first().click().catch(() => {});
await page.waitForTimeout(800);
const rt = await page.evaluate(() => performance.getEntriesByType('resource').map((e) => ({ n: e.name.replace(location.origin, ''), t: e.transferSize, d: e.decodedBodySize })));
const big = rt.filter((r) => r.t > 20000).map((r) => `${r.n.slice(0, 70)}  ${Math.round(r.t / 1024)} KB (${Math.round(r.d / 1024)} KB raw)`);
console.log('large transfers:\n  ' + big.join('\n  '));
console.log('bytes on wire (gzip) by step', Object.fromEntries(Object.entries(per).map(([k, v]) => [k, Math.round(v / 1024) + ' KB'])));
console.log('failed/4xx:', bad.length ? bad : 'none');
await browser.close();
